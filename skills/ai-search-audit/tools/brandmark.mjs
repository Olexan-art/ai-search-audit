// Turns assets/brand/getlooploop-mark.webp into scripts/lib/brandmark.mjs: the GetLoopLoop mark,
// inline, because the report makes no network requests (its CSP allows images from data: only).
// The asset is the real logo (frontend/public/brand/getlooploop-glitch-loop.png in the GetLoopLoop
// repo), trimmed and downscaled to 112 px wide, drawn at 56 px in the header and the footer.
// Run after changing the asset: `node tools/brandmark.mjs`. tests/assets.test.mjs fails if the
// module and the asset disagree.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const root = new URL("../", import.meta.url);
export const MARK_FILE = "assets/brand/getlooploop-mark.webp";

export function brandmarkModule() {
  const uri = `data:image/webp;base64,${readFileSync(new URL(MARK_FILE, root)).toString("base64")}`;
  return [
    "// Generated by tools/brandmark.mjs from assets/brand/getlooploop-mark.webp. Do not edit by hand.",
    "/** The GetLoopLoop mark as a data URI, 112 by 54 pixels. */",
    `export const GLL_MARK = ${JSON.stringify(uri)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(new URL("scripts/lib/brandmark.mjs", root), brandmarkModule());
  console.log("wrote scripts/lib/brandmark.mjs");
}
